static const int kUnitCatCount = sizeof(kUnitCats) / sizeof(kUnitCats[0]);

inline double unitConvert(const UnitCat& c, int a, int b, double v) {
  if (c.temp) {
    double k = (a == 0) ? v + 273.15 : (a == 1) ? (v - 32.0) * 5.0 / 9.0 + 273.15 : v;
    return (b == 0) ? k - 273.15 : (b == 1) ? (k - 273.15) * 9.0 / 5.0 + 32.0 : k;
  }
  return v * c.u[a].k / c.u[b].k;
}
